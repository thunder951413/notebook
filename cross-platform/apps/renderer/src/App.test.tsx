  fireEvent.keyDown(window, { key: 'p', metaKey: true })
  commandPalette = screen.getByRole('dialog', { name: '命令面板' })
  fireEvent.change(within(commandPalette).getByRole('textbox', { name: '搜索命令、页面和设置' }), { target: { value: '同步与连结' } })
  fireEvent.click(within(commandPalette).getByRole('button', { name: /同步与连接/ }))
