  renderedEditor = await screen.findByLabelText('页面正文', {}, { timeout: 5_000 })
  fireEvent.keyDown(renderedEditor, { key: '/' })
  expect(screen.getByRole('search')).toBeInTheDocument()
  expect(screen.getByLabelText('Vim 搜索')).toBeInTheDocument()
  fireEvent.keyDown(screen.getByLabelText('Vim 搜索'), { key: 'Escape' })
  fireEvent.keyDown(renderedEditor, { key: 'i' })
  expect(vimToggle).not.toHaveClass('selected')
  fireEvent.keyDown(renderedEditor, { key: 'Escape' })
  expect(vimToggle).toHaveClass('selected')
  for (const key of ['a', 'A', 'I', 's', 'S']) {
    fireEvent.keyDown(renderedEditor, { key })
    expect(vimToggle).not.toHaveClass('selected')
    fireEvent.keyDown(renderedEditor, { key: 'Escape' })
    expect(vimToggle).toHaveClass('selected')
  }
  const blocksBeforeOpenLine = renderedEditor.childElementCount
  fireEvent.keyDown(renderedEditor, { key: 'o' })
  expect(vimToggle).not.toHaveClass('selected')
  expect(renderedEditor.childElementCount).toBeGreaterThan(blocksBeforeOpenLine)
  fireEvent.keyDown(renderedEditor, { key: 'Escape' })
  const blocksBeforeOpenLineAbove = renderedEditor.childElementCount
  fireEvent.keyDown(renderedEditor, { key: 'O' })
  expect(vimToggle).not.toHaveClass('selected')
  expect(renderedEditor.childElementCount).toBeGreaterThan(blocksBeforeOpenLineAbove)
  fireEvent.keyDown(renderedEditor, { key: 'Escape' })
