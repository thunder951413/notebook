  fireEvent.click(productRoot)
  expect(await within(notebookTree).findByRole('treeitem', { name: 'Notebook Next 产品愿景' })).toBeInTheDocument()
  const directoryHint = await screen.findByRole('note', { name: '目录页提示' })
