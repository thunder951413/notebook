import { fireEvent, render, screen, within } from '@testing-library/react'
import { FluentProvider, webLightTheme } from '@fluentui/react-components'
import { App } from './App'

test('renders the OneNote-style workspace and editor', async () => {
  Object.defineProperty(window, 'matchMedia', { configurable: true, value: (query: string) => ({ matches: query.includes('1301px'), media: query, onchange: null, addListener() {}, removeListener() {}, addEventListener() {}, removeEventListener() {}, dispatchEvent: () => false }) })
  const { container } = render(<FluentProvider theme={webLightTheme}><App /></FluentProvider>)
  expect(screen.getByText('我的知识库')).toBeInTheDocument()
  expect(screen.getAllByText('Notebook Next 产品愿景').length).toBeGreaterThanOrEqual(2)
  expect(await screen.findByLabelText('页面正文')).toBeInTheDocument()
  expect(screen.getByRole('complementary', { name: 'AI 助手' })).toBeInTheDocument()
  expect(screen.getByRole('button', { name: '任务' })).toHaveAttribute('title', '任务')
  expect(screen.queryByRole('img', { name: '闫延' })).not.toBeInTheDocument()
  expect(screen.queryByRole('button', { name: '文件与数据' })).not.toBeInTheDocument()
  expect(screen.queryByText('评论')).not.toBeInTheDocument()
  expect(screen.queryByRole('button', { name: '知识图谱' })).not.toBeInTheDocument()
  expect(screen.queryByRole('button', { name: '画布' })).not.toBeInTheDocument()
  expect(screen.queryByText('共享')).not.toBeInTheDocument()
  expect(screen.queryByText('离线可编辑')).not.toBeInTheDocument()
  expect(screen.queryByText('YY')).not.toBeInTheDocument()
  expect(screen.queryByText('AI')).not.toBeInTheDocument()
  expect(screen.getByRole('button', { name: '版本' })).toBeInTheDocument()
  expect(screen.getAllByRole('button', { name: '新建笔记本' })).toHaveLength(1)
  expect(screen.queryByRole('tooltip')).not.toBeInTheDocument()
  expect(screen.getByRole('tablist', { name: '最近打开的笔记' })).toBeInTheDocument()
  expect(container.querySelector('.document-meta')).not.toBeInTheDocument()
  const pageMode = screen.getByRole('button', { name: /^页面$/ })
  const markdownMode = screen.getByRole('button', { name: /^Markdown$/ })
  expect(pageMode).toHaveAttribute('aria-pressed', 'true')
  expect(markdownMode).toHaveAttribute('aria-pressed', 'false')
  fireEvent.click(markdownMode)
  expect(markdownMode).toHaveAttribute('aria-pressed', 'true')
  expect(pageMode).toHaveAttribute('aria-pressed', 'false')
  fireEvent.click(pageMode)
  const attachmentButton = screen.getByRole('button', { name: /^附件/ })
  const trashButton = screen.getByRole('button', { name: '移到回收站' })
  expect(attachmentButton.compareDocumentPosition(trashButton) & Node.DOCUMENT_POSITION_FOLLOWING).toBeTruthy()

  const pageList = screen.getByRole('complementary', { name: '页面列表' })
  fireEvent.contextMenu(within(pageList).getByRole('button', { name: /Notebook Next 产品愿景/ }))
  const pageActions = await within(container).findByRole('dialog', { name: 'Notebook Next 产品愿景页面操作' })
  expect(within(pageActions).getByRole('button', { name: '取消收藏' })).toBeInTheDocument()
  expect(container.querySelector('.app-shell')).not.toHaveAttribute('aria-hidden', 'true')
  expect(within(pageActions).getByRole('button', { name: '创建副本' })).toBeInTheDocument()
  expect(within(pageActions).getByRole('button', { name: '移动到分区…' })).toBeInTheDocument()
  fireEvent.keyDown(document, { key: 'Escape' })
  fireEvent.keyDown(within(pageList).getByRole('button', { name: /Notebook Next 产品愿景/ }), { key: 'F10', shiftKey: true })
  expect(await within(container).findByRole('dialog', { name: 'Notebook Next 产品愿景页面操作' })).toBeInTheDocument()
  fireEvent.keyDown(document, { key: 'Escape' })

  const notebookTree = screen.getByRole('navigation')
  fireEvent.contextMenu(within(notebookTree).getByRole('button', { name: /^产品设计/ }))
  const sectionActions = await within(container).findByRole('dialog', { name: '产品设计分区操作' })
  expect(within(sectionActions).getByRole('button', { name: '重命名分区' })).toBeInTheDocument()
  expect(within(sectionActions).getByRole('button', { name: '删除分区（需先清空）' })).toBeDisabled()
  fireEvent.keyDown(document, { key: 'Escape' })

  fireEvent.click(within(pageList).getByRole('button', { name: /AI 工作流设计/ }))
  const recentTabs = screen.getByRole('tablist', { name: '最近打开的笔记' })
  expect(within(recentTabs).getByRole('tab', { name: 'AI 工作流设计' })).toHaveAttribute('aria-selected', 'true')
  expect(screen.getByLabelText('页面标题')).toHaveValue('AI 工作流设计')

  fireEvent.click(screen.getByRole('button', { name: '设置' }))
  const settings = screen.getByRole('dialog', { name: '设置' })
  expect(within(settings).getByText('Notebook 设置')).toBeInTheDocument()
  expect(within(settings).getByRole('tab', { name: '常规' })).toBeInTheDocument()
  fireEvent.click(within(settings).getByRole('tab', { name: '数据与备份' }))
  expect(within(settings).getByRole('button', { name: '选择文件并导入' })).toBeInTheDocument()
  expect(within(settings).getByRole('button', { name: '导出完整备份' })).toBeInTheDocument()
  expect(within(settings).getByRole('button', { name: '导出加密备份' })).toBeInTheDocument()
  expect(within(settings).getByRole('button', { name: '导出 Markdown' })).toBeInTheDocument()
  fireEvent.click(within(settings).getByRole('tab', { name: '同步与连接' }))
  expect(within(settings).getByText('SSH/SFTP 同步')).toBeInTheDocument()
  expect(within(settings).getByLabelText('SSH 服务器')).toBeInTheDocument()
  expect(within(settings).getByLabelText('远端同步目录')).toHaveValue('~/notebook_backup')
  expect(within(settings).getByLabelText('SSH 主机指纹')).toBeInTheDocument()
  expect(within(settings).queryByText('Notebook Next HTTP API')).not.toBeInTheDocument()
  expect(within(settings).queryByLabelText('同步服务地址')).not.toBeInTheDocument()
  expect(within(settings).getByRole('button', { name: '保存并立即同步' })).toBeInTheDocument()
  fireEvent.click(within(settings).getByRole('button', { name: '关闭设置' }))
  expect(screen.queryByRole('dialog', { name: '设置' })).not.toBeInTheDocument()

  const pageResizer = screen.getByRole('separator', { name: '调整页面列表宽度' })
  expect(pageResizer).toHaveAttribute('aria-valuenow', '300')
  fireEvent.keyDown(pageResizer, { key: 'ArrowRight' })
  expect(pageResizer).toHaveAttribute('aria-valuenow', '310')

  fireEvent.click(screen.getByRole('button', { name: '页面列表菜单' }))
  expect(await within(container).findByText('按标题排序')).toBeInTheDocument()
  expect(screen.getByText('使用紧凑列表')).toBeInTheDocument()
  fireEvent.click(screen.getByRole('button', { name: '隐藏导航窗格' }))
  expect(screen.queryByLabelText('页面列表')).not.toBeInTheDocument()
  expect(screen.queryByLabelText('笔记本和分区')).not.toBeInTheDocument()
  fireEvent.click(screen.getByRole('button', { name: '显示导航窗格' }))
  expect(screen.getByLabelText('页面列表')).toBeInTheDocument()

  fireEvent.click(screen.getByRole('button', { name: '任务' }))
  expect(screen.getAllByText('所有任务').length).toBeGreaterThanOrEqual(1)
  expect(screen.queryByLabelText('笔记本和分区')).not.toBeInTheDocument()
  const taskList = screen.getByRole('complementary', { name: '页面列表' })
  fireEvent.contextMenu(within(taskList).getByRole('button', { name: /完成跨平台编辑器验收/ }))
  const taskActions = await within(container).findByRole('dialog', { name: '完成跨平台编辑器验收页面操作' })
  expect(within(taskActions).getByRole('button', { name: '标记为已完成' })).toBeInTheDocument()
  expect(within(taskActions).getByRole('button', { name: '取消重要标记' })).toBeInTheDocument()
  expect(within(taskActions).getByRole('button', { name: '1 小时后提醒' })).toBeInTheDocument()
  fireEvent.keyDown(document, { key: 'Escape' })
  fireEvent.click(screen.getByRole('button', { name: '笔记' }))
  expect(screen.getByLabelText('笔记本和分区')).toBeInTheDocument()
  expect(screen.getByLabelText('页面列表')).toBeInTheDocument()

  const rail = screen.getByLabelText('主要功能')
  fireEvent.click(within(rail).getByRole('button', { name: 'AI 助手' }))
  expect(screen.queryByRole('complementary', { name: 'AI 助手' })).not.toBeInTheDocument()
  fireEvent.click(within(rail).getByRole('button', { name: 'AI 助手' }))
  expect(screen.getByRole('complementary', { name: 'AI 助手' })).toBeInTheDocument()

  fireEvent.click(screen.getByRole('button', { name: '进入聚焦模式' }))
  expect(container.querySelector('.app-shell')).toHaveClass('focus-mode')
  fireEvent.keyDown(window, { key: 'Escape' })
  expect(container.querySelector('.app-shell')).not.toHaveClass('focus-mode')
  fireEvent.keyDown(window, { key: 'F11' })
  expect(container.querySelector('.app-shell')).toHaveClass('focus-mode')
  fireEvent.keyDown(window, { key: 'F11' })
  expect(container.querySelector('.app-shell')).not.toHaveClass('focus-mode')
})
