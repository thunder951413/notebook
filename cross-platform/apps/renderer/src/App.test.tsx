  expect(within(settingsFromPalette).getByRole('tab', { name: '同步与连接' })).toHaveAttribute('aria-selected', 'true')
  fireEvent.click(within(settingsFromPalette).getByRole('button', { name: '关闭设置' }))

  fireEvent.keyDown(window, { key: 'p', metaKey: true })
  commandPalette = screen.getByRole('dialog', { name: '命令面板' })
  const referenceHelpSearch = within(commandPalette).getByRole('textbox', { name: '搜索命令、页面和设置' })
  fireEvent.change(referenceHelpSearch, { target: { value: '双链说明' } })
  fireEvent.click(within(commandPalette).getByRole('button', { name: /^双链使用说明/ }))
  const referenceHelp = await screen.findByRole('dialog', { name: '双链使用说明' })
  expect(within(referenceHelp).getByText('把笔记连接成自己的知识网络')).toBeInTheDocument()
  expect(within(referenceHelp).getByText('只显示链接')).toBeInTheDocument()
  expect(within(referenceHelp).getByText('嵌入原文内容')).toBeInTheDocument()
  expect(within(referenceHelp).getByText('固定显示文字')).toBeInTheDocument()
  expect(within(referenceHelp).getByText(/目标改名、移动到其他分区/)).toBeInTheDocument()
  fireEvent.click(within(referenceHelp).getByRole('button', { name: '知道了' }))
  expect(screen.queryByRole('dialog', { name: '双链使用说明' })).not.toBeInTheDocument()

  expect(screen.queryByRole('button', { name: /^源码$/ })).not.toBeInTheDocument()
  expect(screen.queryByRole('group', { name: 'Markdown 编辑视图' })).not.toBeInTheDocument()
  const vimToggle = screen.getByRole('button', { name: 'Vim' })
  fireEvent.click(vimToggle)
  expect(vimToggle).toHaveAttribute('aria-pressed', 'true')
  expect(vimToggle).toHaveClass('selected')
  expect(container.querySelector('.vim-status')).not.toBeInTheDocument()
  let renderedEditor = await screen.findByLabelText('页面正文')
  const beforeVimNavigation = renderedEditor.textContent
  fireEvent.keyDown(renderedEditor, { key: '0' })
  fireEvent.keyDown(renderedEditor, { key: '$' })
  fireEvent.keyDown(renderedEditor, { key: 'p', ctrlKey: true })
  fireEvent.keyDown(renderedEditor, { key: 'n', ctrlKey: true })
  expect(renderedEditor.textContent).toBe(beforeVimNavigation)
